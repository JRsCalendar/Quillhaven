test('deleting a companion revokes sessions and memory but preserves documents, chat and receipts', t => {
  const {store,agent} = fixture(t);
  store.saveMemory('session-a',{expectedMemory:'',memory:'应从活动存档移除的记忆'});
  store.connectAgent({agentId:agent.id},'session-second');
  store.setSetting('automatic',{enabled:true,agentId:agent.id});
  store.sendUserMessage({id:'delete-agent-user',content:'历史提问',recipientIds:[agent.id]});
  store.postReply('session-a',{requestId:'delete-agent-reply',content:'历史回复',replyTo:['delete-agent-user']});
  const before=store.snapshot(),chat=store.exportMessages();
  const removed=store.deleteAgent(agent.id);
  assert.ok(!removed.workspace.agents.some(item=>item.id===agent.id));
  assert.ok(!removed.onlineAgentIds.includes(agent.id));
  assert.deepEqual(removed.workspace.documents,before.workspace.documents);
  assert.deepEqual(store.exportMessages(),chat);
  assert.deepEqual(store.getSetting('automatic'),{enabled:false,agentId:null});
  for(const session of ['session-a','session-second'])assert.throws(()=>store.inbox(session),/先调用 connect_agent/);
  assert.throws(()=>store.connectAgent({agentId:agent.id},'new-session'),/找不到此存档/);
  assert.deepEqual(store.deleteAgent(agent.id).workspace,removed.workspace);
});

