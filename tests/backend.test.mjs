test('chat routing, receipts, idempotent replies and persistent identity memory', t => {
  const {store,agent} = fixture(t);
  const other = store.connectAgent({name:'另一个伙伴'},'session-b').agent;
  const message = store.sendUserMessage({id:'request-1',content:'请润色',recipientIds:[agent.id]});
  store.sendUserMessage({id:'request-1',content:'请润色',recipientIds:[agent.id]});
  assert.equal(store.inbox('session-b').length,0);
  assert.equal(store.inbox('session-a')[0].id,message.id);
  assert.equal(store.inbox('session-a').length,1, 'reading alone does not consume the message');
  const reply = {requestId:'reply-1',content:'已经润色',replyTo:[message.id]};
  store.postReply('session-a',reply); store.postReply('session-a',reply);
  assert.equal(store.exportMessages().length,2);
  assert.equal(store.inbox('session-a').length,0);
  assert.deepEqual(store.exportMessages().find(m=>m.id===message.id).repliedBy,[agent.id]);
  assert.throws(()=>store.postReply('session-b',{...reply,requestId:'bad'}), /发给此伙伴/);
  store.saveMemory('session-a',{expectedMemory:'',memory:'已确认双月，叙述保持克制。'});
  assert.throws(()=>store.saveMemory('session-a',{expectedMemory:'',memory:'覆盖'}), /已经更新/);
  store.disconnect('session-a');
  assert.ok(!store.snapshot().onlineAgentIds.includes(agent.id));
  assert.equal(store.connectAgent({agentId:agent.id},'session-new').agent.memory,'已确认双月，叙述保持克制。');
  assert.equal(store.connectAgent({agentId:other.id},'session-b').agent.id,other.id);
});
test('document edits are atomic, versioned, and reject stale or ambiguous replacements', t => {
  const {store,doc} = fixture(t);
  const current = store.readDocument(doc.id);
  const changed = store.editDocument('session-a',{id:doc.id,expectedRevision:current.revision,edits:[{oldText:doc.content,newText:'双月从海面升起。'}]});
  assert.equal(changed.revision,current.revision+1);
  assert.throws(()=>store.editDocument('session-a',{id:doc.id,expectedRevision:current.revision,edits:[{oldText:'',newText:'错误覆盖'}]}),/文档已更新/);
  assert.throws(()=>store.editDocument('session-a',{id:doc.id,expectedRevision:changed.revision,edits:[{oldText:'双月',newText:'月亮'},{oldText:'不存在',newText:'失败'}]}),/精确/);
  assert.equal(store.readDocument(doc.id).content,'双月从海面升起。');
  assert.equal(store.documentHistory(doc.id)[0].document.content,doc.content);
});
test('browser/MCP concurrency merges independent changes and preserves conflicting prose', t => {
  const {store,doc} = fixture(t);
  const base = store.snapshot().workspace;
  store.editDocument('session-a',{id:doc.id,expectedRevision:1,edits:[{oldText:doc.content,newText:'Agent 的改写'}]});
  const local = structuredClone(base); local.documents[0].title = '新的标题';
  let result = store.syncWorkspace(base,local);
  assert.equal(result.workspace.documents[0].content,'Agent 的改写');
  assert.equal(result.workspace.documents[0].title,'新的标题');
  local.documents[0].content = '用户的改写';
  result = store.syncWorkspace(base,local);
  assert.equal(result.workspace.documents.length,2);
  assert.ok(result.workspace.documents.some(d=>d.content==='Agent 的改写'));
  assert.ok(result.workspace.documents.some(d=>d.content==='用户的改写' && d.title.includes('冲突副本')));
  assert.ok(result.conflicts.length);
});
